const PLUGIN_ROOT = resolve(import.meta.dirname, '..', '..');
/**
 * Stable statusline indirection (fixes R-07): the settings point at a shim in
 * the user-scope config dir; the shim follows `plugin-root`, which the
 * SessionStart hook refreshes from CLAUDE_PLUGIN_ROOT every session, so plugin
 * updates (new versioned install paths) never break the HUD.
 */
export function shimPath(): string {
  return join(userConfigDir(), 'statusline.sh');
}

export function pluginRootPointer(): string {
  return join(userConfigDir(), 'plugin-root');
}

export function statuslineCommand(): string {
  return `"${shimPath()}"`;
}

function shimScript(): string {
  const pointer = pluginRootPointer().replaceAll('"', '');
  const fallback = PLUGIN_ROOT.replaceAll('"', '');
  return `#!/bin/sh
# Kilamu Code statusline shim (generated by \`kilamu statusline install\`).
# Follows the plugin root recorded by the SessionStart hook so plugin updates
# never break the HUD. Safe to delete; \`kilamu statusline uninstall\` restores settings.
ROOT=""
[ -f "${pointer}" ] && ROOT="$(head -n 1 "${pointer}")"
[ -x "$ROOT/bin/kilamu" ] || ROOT="${fallback}"
exec "$ROOT/bin/kilamu" statusline
`;
}

/** Record where the plugin currently lives (SessionStart hook + install). Cheap, idempotent, symlink-safe. */
export function recordPluginRoot(root: string): void {
  if (!root || /[\r\n]/.test(root) || !existsSync(join(root, 'bin', 'kilamu'))) return;
  const pointer = pluginRootPointer();
  try {
    if (existsSync(pointer) && readFileSync(pointer, 'utf8').trim() === root) return;
    mkdirSync(userConfigDir(), { recursive: true, mode: 0o700 });
    writeFileAtomic(pointer, `${root}\n`, { refuseSymlinkTarget: true });
  } catch {
    // best effort: the shim falls back to the install-time root
  }
}

/** Is this statusLine command one Kilamu installed (current shim or legacy direct path)? */
function isKilamuCommand(cmd: unknown): boolean {
  return typeof cmd === 'string' && (cmd === statuslineCommand() || /bin\/kilamu"? statusline/.test(cmd));
}

function obj(v: unknown): Record<string, unknown> {
  return typeof v === 'object' && v !== null && !Array.isArray(v) ? (v as Record<string, unknown>) : {};
}

function usageFromSample(s: UsageSample | null, payloadModel: string | null): HudState['usage'] {
  const src = 'statusline';
  if (!s) {
    return { model: payloadModel, tokens: unavailable(src), costUsd: unavailable(src), contextPct: unavailable(src), durationMs: unavailable(src), cacheHitRatio: unavailable(src) };
  }
  const tokens = s.inputTokens !== null || s.outputTokens !== null ? (s.inputTokens ?? 0) + (s.outputTokens ?? 0) : null;
  return {
    model: s.model ?? payloadModel,
    tokens: tokens !== null ? measured(tokens, `${src}:context_window.total_*_tokens`) : unavailable(src),
    costUsd: s.costUsd !== null ? measured(s.costUsd, `${src}:cost.total_cost_usd`) : unavailable(src),
    contextPct: s.contextUsedPct !== null ? measured(s.contextUsedPct, `${src}:context_window.used_percentage`) : unavailable(src),
    durationMs: s.durationMs !== null ? measured(s.durationMs, `${src}:cost.total_duration_ms`) : unavailable(src),
    cacheHitRatio: unavailable(src),
  };
}

/** Build the HUD state from durable state + the latest measured sample. No model calls, no indexing. */
export function buildHudState(app: App | null, sample: UsageSample | null, payload: unknown): HudState {
  const p = obj(payload);
  const model = typeof obj(p.model).display_name === 'string' ? (obj(p.model).display_name as string) : null;
  const usage = usageFromSample(sample, model);
  const hitRatio = obj(p.prompt_cache).hit_ratio;
  if (typeof hitRatio === 'number' && Number.isFinite(hitRatio)) usage.cacheHitRatio = measured(hitRatio, 'statusline:prompt_cache.hit_ratio');
  const state: HudState = { execution: null, usage, budgetRemainingPct: unavailable('no active execution') };
  if (!app) return state;
  const ex = app.executions.activeExecution();
  if (!ex) return state;
  const s = app.executions.summary(ex.id);
  const running = s.tasks.filter((t) => t.status === 'RUNNING' || t.status === 'VERIFYING').map((t) => ({ taskId: t.id, role: t.role, title: t.title }));
  const next = s.tasks.find((t) => t.status === 'READY');
  const lastVerified = app.executions.taskEvents(ex.id, undefined, 50).find((e) => e.to === 'VERIFIED');
  state.execution = {
    id: ex.id, objective: ex.objective, status: ex.status, mode: ex.mode, teamSize: ex.modeRationale.teamSize,
    progressPct: s.progressPct, counts: s.counts, total: s.total, running,
    next: next ? `${next.id} ${next.title}` : null,
    blockers: s.blocked,
    lastVerified: lastVerified ? lastVerified.taskId : null,
    budgetTokens: ex.budgetTokens,
  };
  const sid = sample?.sessionId ?? null;
  const delta = sid ? app.usage.deltaSince(sid, ex.createdAt) : null;
  if (delta && (delta.inputTokens !== null || delta.outputTokens !== null)) {
    const used = (delta.inputTokens ?? 0) + (delta.outputTokens ?? 0);
    state.budgetRemainingPct = measured(Math.max(0, Math.round(100 - (used / ex.budgetTokens) * 100)), 'statusline token delta since execution start');
  }
  return state;
}

/** Render mode: invoked by Claude Code with the session JSON on stdin. Never throws. */
export async function renderFromStdin(): Promise<string> {
  let raw = '';
  try {
    raw = await readStdin(1024 * 1024);
  } catch {
    return 'KILAMU';
  }
  const payload = parseStatuslinePayload(raw);
  const p = obj(payload);
  const ws = obj(p.workspace);
  const root = typeof ws.project_dir === 'string' ? ws.project_dir : typeof p.cwd === 'string' ? p.cwd : process.cwd();
  const color = !process.env.NO_COLOR;
  if (!isInitialized(projectPaths(root))) {
    return renderStatusline(buildHudState(null, null, payload), { color });
  }
  let app: App | null = null;
  try {
    app = App.open(root);
    const sample = app.usage.recordStatusline(payload);
    if (sample?.sessionId) app.setSessionId(sample.sessionId);
    return renderStatusline(buildHudState(app, sample, payload), { color });
  } catch {
    return renderStatusline(buildHudState(null, null, payload), { color });
  } finally {
    app?.close();
  }
}

// ------------------------------------------------------------- install/remove

interface Backup {
  installedCommand: string;
  previous: unknown;
  installedAt: string;
}

function settingsFile(scope: string, root: string): string {
  if (scope === 'project') return join(root, '.claude', 'settings.local.json');
  if (scope === 'user') return join(homedir(), '.claude', 'settings.json');
  throw new KilamuError('USAGE', '--scope must be project or user');
}

function readSettings(file: string): Record<string, unknown> {
  if (!existsSync(file)) return {};
  try {
    const v = JSON.parse(readFileSync(file, 'utf8')) as unknown;
    if (typeof v !== 'object' || v === null || Array.isArray(v)) throw new Error('not an object');
    return v as Record<string, unknown>;
  } catch (e) {
    throw new KilamuError('SETTINGS_INVALID', `Refusing to modify ${file}: it is not valid JSON (${(e as Error).message})`);
  }
}

function writeAtomic(file: string, data: string): void {
  mkdirSync(dirname(file), { recursive: true });
  // Settings may live in a cloned repo's .claude/: never write through planted symlinks.
  writeFileAtomic(file, data, { refuseSymlinkTarget: true });
}

export function cmdStatuslineAdmin(root: string, argv: string[]): CommandResult {
  const { sub, p } = parseSub(argv, { scope: { type: 'string' }, 'dry-run': { type: 'boolean' }, force: { type: 'boolean' } });
  const scope = str(p, 'scope') ?? 'project';
  const file = settingsFile(scope, root);
  const backupFile = `${file}.kilamu-statusline-backup.json`;
  const settings = readSettings(file);
  const current = settings.statusLine;
  if (sub === 'install') {
    const desired = { type: 'command', command: statuslineCommand(), padding: 0 };
    if (current !== undefined && JSON.stringify(current) === JSON.stringify(desired)) return { data: { file, unchanged: true }, text: `Already installed in ${file}` };
    if (current !== undefined && !flag(p, 'force')) {
      throw new KilamuError('STATUSLINE_EXISTS', `${file} already has a statusLine (${JSON.stringify(current)}). Re-run with --force to replace it (a backup is kept and \`kilamu statusline uninstall\` restores it).`);
    }
    const next = { ...settings, statusLine: desired };
    if (flag(p, 'dry-run')) return { data: { file, statusLine: desired }, text: `Would set in ${file}:\n${JSON.stringify({ statusLine: desired }, null, 2)}` };
    if (isSymlink(file) || isSymlink(dirname(file))) throw new KilamuError('UNSAFE_PATH', `Refusing to modify symlinked settings path ${file}`);
    mkdirSync(userConfigDir(), { recursive: true, mode: 0o700 });
    writeFileAtomic(shimPath(), shimScript(), { mode: 0o700, refuseSymlinkTarget: true });
    recordPluginRoot(PLUGIN_ROOT);
    if (existsSync(file)) copyFileExclusive(file, `${file}.kilamu-bak-${Date.now()}`);
    // Re-installing over our own (e.g. stale-path) statusline must keep the user's ORIGINAL as the restore target.
    const prior = existsSync(backupFile) ? (parseJsonStrict(readFileSync(backupFile, 'utf8'), 'statusline backup') as Backup) : null;
    const currentIsKilamu = isKilamuCommand((current as { command?: unknown } | undefined)?.command);
    const previous = prior && currentIsKilamu ? prior.previous : (current ?? null);
    const backup: Backup = { installedCommand: statuslineCommand(), previous, installedAt: new Date().toISOString() };
    writeAtomic(backupFile, `${JSON.stringify(backup, null, 2)}\n`);
    writeAtomic(file, `${JSON.stringify(next, null, 2)}\n`);
    return { data: { file, statusLine: desired }, text: `Installed Kilamu HUD in ${file}. It takes effect on the next statusline refresh. Undo with: kilamu statusline uninstall --scope ${scope}\nThe statusline runs ${shimPath()}, which follows plugin updates automatically.` };
  }
  if (sub === 'uninstall') {
    if (!existsSync(backupFile)) throw new KilamuError('NOT_FOUND', `No Kilamu statusline backup at ${backupFile}; nothing to restore`);
    const backup = parseJsonStrict(readFileSync(backupFile, 'utf8'), 'statusline backup') as Backup;
    const cur = current as { command?: string } | undefined;
    if (!cur || cur.command !== backup.installedCommand) {
      throw new KilamuError('STATUSLINE_CHANGED', `The statusLine in ${file} is no longer the one Kilamu installed; leaving it untouched`);
    }
    const next = { ...settings };
    if (backup.previous === null) delete next.statusLine;
    else next.statusLine = backup.previous;
    if (flag(p, 'dry-run')) return { data: { file, restore: backup.previous }, text: `Would restore statusLine in ${file} to ${JSON.stringify(backup.previous)}` };
    writeAtomic(file, `${JSON.stringify(next, null, 2)}\n`);
    renameSync(backupFile, `${backupFile}.restored-${Date.now()}`);
    return { data: { file, restored: backup.previous }, text: `Restored previous statusLine in ${file}` };
  }
  throw new KilamuError('USAGE', 'usage: kilamu statusline [install|uninstall] [--scope project|user] [--dry-run] [--force]');
}

/** For doctor: is a Kilamu statusline configured, and does its path still exist? */
export function statuslineDiagnostic(root: string): { name: string; status: 'ok' | 'warn' | 'fail'; detail: string } {
  for (const scope of ['project', 'user']) {
    let s: Record<string, unknown>;
    try {
      s = readSettings(settingsFile(scope, root));
    } catch {
      continue;
    }
    const cmd = obj(s.statusLine).command;
    if (isKilamuCommand(cmd)) {
      if (cmd === statuslineCommand()) {
        if (!existsSync(shimPath())) return { name: 'statusline', status: 'warn', detail: `${scope} statusline shim ${shimPath()} is missing; re-run kilamu statusline install --force --scope ${scope}` };
        return { name: 'statusline', status: 'ok', detail: `installed (${scope}, update-safe shim)` };
      }
      const m = /"([^"]+bin\/kilamu)"/.exec(String(cmd));
      if (m && !existsSync(m[1]!)) return { name: 'statusline', status: 'warn', detail: `${scope} statusline points to a missing path (${m[1]}); re-run kilamu statusline install --force --scope ${scope}` };
      return { name: 'statusline', status: 'warn', detail: `installed (${scope}) with a version-specific path; re-run install --force to switch to the update-safe shim` };
    }
  }
  return { name: 'statusline', status: 'warn', detail: 'not installed (optional): kilamu statusline install --dry-run' };
}
