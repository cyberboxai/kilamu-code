import { existsSync, lstatSync, mkdirSync, readFileSync, realpathSync, statSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { KilamuError } from './errors.ts';
import { writeFileExclusive } from './fsx.ts';

export const DATA_DIR_NAME = '.kilamu';

export interface ProjectPaths {
  root: string;
  dataDir: string;
  stateDir: string;
  dbFile: string;
  memoryDir: string;
  indexDir: string;
  artifactsDir: string;
  cacheDir: string;
  logsDir: string;
  configFile: string;
}

/**
 * Resolve the project root: explicit arg → KILAMU_PROJECT_DIR → CLAUDE_PROJECT_DIR
 * → nearest ancestor containing .git or .kilamu → cwd.
 */
export function findProjectRoot(start?: string): string {
  const explicit = start ?? process.env.KILAMU_PROJECT_DIR ?? process.env.CLAUDE_PROJECT_DIR;
  if (explicit) return resolve(explicit);
  let dir = resolve(process.cwd());
  for (;;) {
    if (existsSync(join(dir, '.git')) || existsSync(join(dir, DATA_DIR_NAME))) return dir;
    const parent = dirname(dir);
    if (parent === dir) return resolve(process.cwd());
    dir = parent;
  }
}

export function projectPaths(root: string): ProjectPaths {
  const dataDir = process.env.KILAMU_DATA_DIR ? resolve(process.env.KILAMU_DATA_DIR) : join(root, DATA_DIR_NAME);
  const stateDir = join(dataDir, 'state');
  return {
    root,
    dataDir,
    stateDir,
    dbFile: join(stateDir, 'execution.db'),
    memoryDir: join(dataDir, 'memory'),
    indexDir: join(dataDir, 'index'),
    artifactsDir: join(dataDir, 'artifacts'),
    cacheDir: join(dataDir, 'cache'),
    logsDir: join(dataDir, 'logs'),
    configFile: join(dataDir, 'config.json'),
  };
}

/** Contents of the generated .kilamu/.gitignore: everything transient stays local. */
const DATA_GITIGNORE = `# Generated by Kilamu Code. Local, transient data — do not commit.
*
!.gitignore
`;

/** Create the data directory tree (idempotent). Never touches the project's own .gitignore. */
export function ensureDataDirs(p: ProjectPaths): void {
  for (const d of [p.dataDir, p.stateDir, p.memoryDir, p.indexDir, p.artifactsDir, p.cacheDir, p.logsDir]) {
    if (existsSync(d)) {
      const st = lstatSync(d);
      if (st.isSymbolicLink()) throw new KilamuError('UNSAFE_PATH', `Refusing to use symlinked data directory: ${d}`);
      if (!st.isDirectory()) throw new KilamuError('UNSAFE_PATH', `Data path exists and is not a directory: ${d}`);
    } else {
      mkdirSync(d, { recursive: true, mode: 0o700 });
    }
  }
  const gi = join(p.dataDir, '.gitignore');
  try {
    // O_EXCL|O_NOFOLLOW: never write through a (dangling) planted symlink.
    writeFileExclusive(gi, DATA_GITIGNORE);
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code !== 'EEXIST') throw e;
    if (lstatSync(gi).isSymbolicLink()) throw new KilamuError('UNSAFE_PATH', `Refusing symlinked ${gi}`);
  }
}

/**
 * User-scope Kilamu directory (outside any project): trust records and the
 * verification policy extensions live here so repository content and the
 * model cannot change them. KILAMU_CONFIG_HOME overrides (tests).
 */
export function userConfigDir(): string {
  if (process.env.KILAMU_CONFIG_HOME) return resolve(process.env.KILAMU_CONFIG_HOME);
  const xdg = process.env.XDG_CONFIG_HOME;
  return join(xdg ? resolve(xdg) : join(homedir(), '.config'), 'kilamu-code');
}

/** True if `child` is `parent` or inside it (lexical check on resolved paths). */
export function isInside(parent: string, child: string): boolean {
  const rel = relative(parent, child);
  return rel === '' || (!rel.startsWith('..') && !isAbsolute(rel));
}

/**
 * Resolve a user/agent supplied path against the project root and ensure it
 * cannot escape the root, lexically or through symlinks.
 */
export function safeResolve(root: string, p: string): string {
  if (p.includes('\0')) throw new KilamuError('UNSAFE_PATH', 'Path contains NUL byte');
  const abs = resolve(root, p);
  if (!isInside(root, abs)) throw new KilamuError('UNSAFE_PATH', `Path escapes project root: ${p}`);
  if (existsSync(abs)) {
    const real = realpathSync(abs);
    const realRoot = realpathSync(root);
    if (!isInside(realRoot, real)) throw new KilamuError('UNSAFE_PATH', `Path resolves outside project root via symlink: ${p}`);
  }
  return abs;
}

/** Project-relative POSIX path. */
export function toRel(root: string, abs: string): string {
  return relative(root, abs).split(sep).join('/');
}

// ---------------------------------------------------------------------------
// Sensitive / irrelevant path policy (directive §17)
// ---------------------------------------------------------------------------

const SENSITIVE_BASENAME = [
  /^\.env$/i,
  /^\.env\.(?!example$|sample$|template$|dist$).+/i,
  /\.pem$/i,
  /\.key$/i,
  /\.p12$/i,
  /\.pfx$/i,
  /\.jks$/i,
  /\.keystore$/i,
  /\.kdbx?$/i,
  /^\.?netrc$/i,
  /^\.npmrc$/i,
  /^\.pypirc$/i,
  /^\.pgpass$/i,
  /^\.htpasswd$/i,
  /^credentials(\..*)?$/i,
  /^secrets?(\..*)?$/i,
  /^.*\.secret(s)?(\..*)?$/i,
  /^service-account.*\.json$/i,
  /^.*\.tfstate(\.backup)?$/i,
  /^.*\.tfvars(\.json)?$/i,
  /^\.envrc$/i,
  /^\.dev\.vars$/i,
  /^\.git-credentials$/i,
  /^\.vault-token$/i,
  /^\.s3cfg$/i,
  /^kubeconfig(\..*)?$/i,
  /\.ppk$/i,
  /^id_(rsa|dsa|ecdsa|ed25519)(_sk)?(\.pub)?$/i,
];

const SENSITIVE_DIR = new Set(['.ssh', '.gnupg', '.aws', '.azure', '.kube', '.docker', '.password-store', 'secrets']);

/** Directories never indexed: dependencies, build output, VCS, our own data. */
export const IGNORED_DIRS = new Set([
  '.git', 'node_modules', DATA_DIR_NAME, '.omc', 'dist', 'build', 'out', 'coverage', '.next', '.nuxt',
  '.venv', 'venv', 'env', '__pycache__', '.mypy_cache', '.pytest_cache', '.ruff_cache', '.tox',
  'target', 'vendor', '.gradle', '.idea', '.vscode', '.cache', '.turbo', '.parcel-cache', 'bower_components',
]);

/** True if any segment of the relative path marks it as sensitive. */
export function isSensitivePath(relPath: string): boolean {
  const parts = relPath.split(/[\\/]/).filter(Boolean);
  const base = parts[parts.length - 1] ?? '';
  if (parts.slice(0, -1).some((d) => SENSITIVE_DIR.has(d.toLowerCase()))) return true;
  return SENSITIVE_BASENAME.some((re) => re.test(base));
}

export function isIgnoredDir(name: string): boolean {
  return IGNORED_DIRS.has(name);
}

/**
 * Read a project file named by a CLI argument: confined to the root (lexical
 * + realpath), refuses sensitive paths, bounded size. Callers must not echo
 * the content in error messages.
 */
export function readProjectFile(root: string, rel: string, maxBytes = 8 * 1024 * 1024): string {
  const abs = safeResolve(root, rel);
  const r = toRel(root, abs);
  // Check both the named path and what it resolves to (a symlink named notes.txt → .env).
  const real = existsSync(abs) ? toRel(realpathSync(root), realpathSync(abs)) : r;
  if (isSensitivePath(r) || isSensitivePath(real)) throw new KilamuError('SENSITIVE_PATH', `Refusing to read sensitive file ${r}`);
  if (!existsSync(abs) || !statSync(abs).isFile()) throw new KilamuError('NOT_FOUND', `File not found: ${r}`);
  if (statSync(abs).size > maxBytes) throw new KilamuError('INPUT_TOO_LARGE', `${r} exceeds ${maxBytes} bytes`);
  return readFileSync(abs, 'utf8');
}

/** JSON.parse without echoing input fragments in the error (they may hold secrets). */
export function parseJsonStrict(text: string, what: string): unknown {
  try {
    return JSON.parse(text) as unknown;
  } catch {
    throw new KilamuError('INVALID_JSON', `${what} is not valid JSON`);
  }
}
